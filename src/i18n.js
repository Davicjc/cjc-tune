const STRINGS = { en, pt, es, zh };

/** A translator for one language; unknown keys fall back to English, then to the key. */
export function makeT(lang) {
    const table = STRINGS[lang] ?? en;
    return (key, vars) => {
        let text = table[key] ?? en[key] ?? key;
        if (vars) {
            for (const [name, value] of Object.entries(vars)) {
                text = text.replaceAll(`{${name}}`, value);
            }
        }
        return text;
    };
}

/** Message from the backend: known codes and audio-status texts are translated, anything else is shown as is. */
export function translateMessage(t, message) {
    if (!message) return message;
    const text = String(message);
    if (text.startsWith("error.")) return t(text);
    const audioKey = `audio.${text}`;
    const translated = t(audioKey);
    return translated === audioKey ? text : translated;
}

export const I18nContext = createContext(makeT("pt"));

export function useT() {
    return useContext(I18nContext);
}

/** Every language must define every key. */
export function missingKeys() {
    const keys = Object.keys(en);
    return Object.fromEntries(
        Object.entries(STRINGS).map(([code, table]) => [code, keys.filter((k) => !(k in table))]),
    );
}
